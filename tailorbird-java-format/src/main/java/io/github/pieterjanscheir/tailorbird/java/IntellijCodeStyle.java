package io.github.pieterjanscheir.tailorbird.java;

import com.google.common.collect.ImmutableList;
import java.util.ArrayList;
import java.util.List;
import java.util.Locale;
import javax.annotation.Nullable;

/**
 * Tailorbird: an IntelliJ IDEA code style that matches a set of {@link TailorbirdRules}, as a code style scheme XML (for
 * <em>Settings | Editor | Code Style | Import Scheme</em>) or as the {@code ij_java_*} keys of an {@code .editorconfig}.
 *
 * <p>With the exported style, IntelliJ's <em>Reformat Code</em> leaves Tailorbird's output unchanged. IntelliJ keeps
 * the line breaks it finds, so it doesn't undo Tailorbird's wrapping, but it also doesn't wrap new code the way
 * Tailorbird does. {@link #unsupported} lists the settings in use that IntelliJ has no equivalent for.
 */
public final class IntellijCodeStyle {

    /** What to export, picked with {@code --export-intellij-style} or {@code --export-editorconfig}. */
    public enum Format {
        INTELLIJ_STYLE,
        EDITORCONFIG
    }

    private enum Section {
        /** {@code <JavaCodeStyleSettings>}. */
        JAVA,
        /** {@code <codeStyleSettings language="JAVA">}. */
        LANGUAGE,
        /** {@code <indentOptions>} inside the language section. */
        INDENT
    }

    private static final class Option {
        final Section section;
        final String ideaName;
        final String editorConfigKey;
        final String value;

        Option(Section section, String ideaName, String editorConfigKey, Object value) {
            this.section = section;
            this.ideaName = ideaName;
            this.editorConfigKey = editorConfigKey;
            this.value = String.valueOf(value);
        }
    }

    private static final ImmutableList<String> CONTROL_KEYWORDS =
            ImmutableList.of("if", "for", "while", "switch", "try", "catch", "synchronized");

    private IntellijCodeStyle() {}

    /** The export in {@code format}. */
    public static String export(TailorbirdRules rules, Format format) {
        switch (format) {
            case INTELLIJ_STYLE:
                return schemeXml(rules);
            case EDITORCONFIG:
                return editorConfig(rules);
        }
        throw new IllegalArgumentException("Unknown format: " + format);
    }

    /**
     * The settings in {@code rules} that IntelliJ can't express, with what IntelliJ does instead. With these, IntelliJ
     * changes some of Tailorbird's output.
     */
    static ImmutableList<String> unsupported(TailorbirdRules rules) {
        ImmutableList.Builder<String> result = ImmutableList.builder();
        if (rules.blankLinesAroundFieldsWithJavadoc()
                && !rules.blankLinesBetweenFields()
                && !rules.keepTypedBlankLines()) {
            result.add("blankLines.aroundFieldsWithJavadoc: IntelliJ has no setting for blank lines around only the"
                    + " fields with JavaDoc, and removes them.");
        }
        if (rules.javadocLayout() && !rules.javadocSingleSpaceAfterTagName()) {
            result.add("javadoc.singleSpaceAfterTagName: false: IntelliJ can't keep the spacing as typed, and puts one"
                    + " space after a @param or @throws name.");
        }
        return result.build();
    }

    /** A code style scheme, the format of IntelliJ's <em>Export | IntelliJ IDEA code style XML</em>. */
    static String schemeXml(TailorbirdRules rules) {
        List<Option> options = options(rules);
        StringBuilder xml = new StringBuilder();
        xml.append("<!-- Generated by Tailorbird from tailorbird.yml.");
        for (String unsupported : unsupported(rules)) {
            xml.append("\n     Not expressible: ").append(unsupported);
        }
        xml.append(" -->\n");
        xml.append("<code_scheme name=\"Tailorbird\" version=\"173\">\n");
        xml.append("  <JavaCodeStyleSettings>\n");
        appendOptions(xml, options, Section.JAVA, "    ");
        xml.append("    <option name=\"IMPORT_LAYOUT_TABLE\">\n");
        xml.append("      <value>\n");
        for (ImportEntry entry : importLayout(rules)) {
            xml.append("        ").append(entry.xml()).append('\n');
        }
        xml.append("      </value>\n");
        xml.append("    </option>\n");
        xml.append("  </JavaCodeStyleSettings>\n");
        xml.append("  <codeStyleSettings language=\"JAVA\">\n");
        appendOptions(xml, options, Section.LANGUAGE, "    ");
        xml.append("    <indentOptions>\n");
        appendOptions(xml, options, Section.INDENT, "      ");
        xml.append("    </indentOptions>\n");
        xml.append("  </codeStyleSettings>\n");
        xml.append("</code_scheme>\n");
        return xml.toString();
    }

    /** The {@code [*.java]} section of an {@code .editorconfig}. */
    static String editorConfig(TailorbirdRules rules) {
        StringBuilder config = new StringBuilder();
        config.append("# Generated by Tailorbird from tailorbird.yml.\n");
        for (String unsupported : unsupported(rules)) {
            config.append("# Not expressible: ").append(unsupported).append('\n');
        }
        config.append("[*.java]\n");
        config.append("indent_style = space\n");
        for (Option option : options(rules)) {
            config.append(option.editorConfigKey)
                    .append(" = ")
                    .append(option.value)
                    .append('\n');
        }
        List<String> layout = new ArrayList<>();
        for (ImportEntry entry : importLayout(rules)) {
            layout.add(entry.editorConfig());
        }
        config.append("ij_java_imports_layout = ")
                .append(String.join(",", layout))
                .append('\n');
        return config.toString();
    }

    private static List<Option> options(TailorbirdRules rules) {
        List<Option> options = new ArrayList<>();

        // Layout
        options.add(new Option(Section.LANGUAGE, "RIGHT_MARGIN", "max_line_length", rules.lineLength()));
        options.add(new Option(Section.INDENT, "INDENT_SIZE", "indent_size", rules.indent()));
        options.add(new Option(
                Section.INDENT, "CONTINUATION_INDENT_SIZE", "ij_continuation_indent_size", rules.continuationIndent()));

        // Spaces
        for (String keyword : CONTROL_KEYWORDS) {
            options.add(new Option(
                    Section.LANGUAGE,
                    "SPACE_BEFORE_" + keyword.toUpperCase(Locale.ROOT) + "_PARENTHESES",
                    "ij_java_space_before_" + keyword + "_parentheses",
                    rules.spaceAfterControlKeyword()));
        }
        options.add(new Option(
                Section.LANGUAGE,
                "SPACE_WITHIN_ARRAY_INITIALIZER_BRACES",
                "ij_java_spaces_within_array_initializer_braces",
                rules.arrayInitializerBraceSpaces()));
        // Tailorbird and upstream always write new int[] {...}.
        options.add(new Option(
                Section.LANGUAGE,
                "SPACE_BEFORE_ARRAY_INITIALIZER_LBRACE",
                "ij_java_space_before_array_initializer_left_brace",
                true));

        // Wrapping
        options.add(new Option(
                Section.LANGUAGE,
                "CALL_PARAMETERS_RPAREN_ON_NEXT_LINE",
                "ij_java_call_parameters_right_paren_on_new_line",
                rules.closingParenOnOwnLine()));
        options.add(new Option(
                Section.LANGUAGE,
                "METHOD_PARAMETERS_RPAREN_ON_NEXT_LINE",
                "ij_java_method_parameters_right_paren_on_new_line",
                rules.closingParenOnOwnLine()));
        options.add(new Option(
                Section.LANGUAGE,
                "KEEP_CONTROL_STATEMENT_IN_ONE_LINE",
                "ij_java_keep_control_statement_in_one_line",
                !rules.bodyWithoutBracesOnOwnLine()));
        // Tailorbird and upstream keep empty bodies on one line: void f() {}, class A {}, () -> {}.
        options.add(new Option(
                Section.LANGUAGE, "KEEP_SIMPLE_BLOCKS_IN_ONE_LINE", "ij_java_keep_simple_blocks_in_one_line", true));
        options.add(new Option(
                Section.LANGUAGE, "KEEP_SIMPLE_METHODS_IN_ONE_LINE", "ij_java_keep_simple_methods_in_one_line", true));
        options.add(new Option(
                Section.LANGUAGE, "KEEP_SIMPLE_LAMBDAS_IN_ONE_LINE", "ij_java_keep_simple_lambdas_in_one_line", true));
        options.add(new Option(
                Section.LANGUAGE, "KEEP_SIMPLE_CLASSES_IN_ONE_LINE", "ij_java_keep_simple_classes_in_one_line", true));

        // Blank lines
        int keepBlankLines = rules.keepTypedBlankLines() ? 1 : 0;
        options.add(new Option(
                Section.LANGUAGE,
                "KEEP_BLANK_LINES_IN_DECLARATIONS",
                "ij_java_keep_blank_lines_in_declarations",
                keepBlankLines));
        options.add(new Option(
                Section.LANGUAGE, "KEEP_BLANK_LINES_IN_CODE", "ij_java_keep_blank_lines_in_code", keepBlankLines));
        // Tailorbird's blank line before a class's closing brace: IntelliJ removes it in some classes unless it may
        // keep one there. With the setting at 1, IntelliJ also keeps a typed blank line before other closing braces.
        options.add(new Option(
                Section.LANGUAGE,
                "KEEP_BLANK_LINES_BEFORE_RBRACE",
                "ij_java_keep_blank_lines_before_right_brace",
                rules.keepTypedBlankLines() || rules.blankLinesAroundClassBody() ? 1 : 0));
        int classBody = rules.blankLinesAroundClassBody() ? 1 : 0;
        options.add(new Option(
                Section.LANGUAGE,
                "BLANK_LINES_AFTER_CLASS_HEADER",
                "ij_java_blank_lines_after_class_header",
                classBody));
        options.add(new Option(
                Section.LANGUAGE, "BLANK_LINES_BEFORE_CLASS_END", "ij_java_blank_lines_before_class_end", classBody));
        options.add(new Option(
                Section.LANGUAGE,
                "BLANK_LINES_AFTER_ANONYMOUS_CLASS_HEADER",
                "ij_java_blank_lines_after_anonymous_class_header",
                classBody));
        options.add(new Option(
                Section.LANGUAGE,
                "BLANK_LINES_AROUND_FIELD",
                "ij_java_blank_lines_around_field",
                rules.blankLinesBetweenFields() ? 1 : 0));
        options.add(new Option(
                Section.LANGUAGE,
                "BLANK_LINES_AROUND_METHOD_IN_INTERFACE",
                "ij_java_blank_lines_around_method_in_interface",
                rules.blankLinesAroundInterfaceMethods() ? 1 : 0));

        // Imports: Tailorbird never writes wildcard imports.
        options.add(new Option(
                Section.JAVA,
                "CLASS_COUNT_TO_USE_IMPORT_ON_DEMAND",
                "ij_java_class_count_to_use_import_on_demand",
                999));
        options.add(new Option(
                Section.JAVA,
                "NAMES_COUNT_TO_USE_IMPORT_ON_DEMAND",
                "ij_java_names_count_to_use_import_on_demand",
                999));
        options.add(new Option(
                Section.JAVA,
                "LAYOUT_STATIC_IMPORTS_SEPARATELY",
                "ij_java_layout_static_imports_separately",
                rules.importGroups().contains(TailorbirdRules.STATIC_IMPORTS)));

        // JavaDoc
        options.add(new Option(
                Section.JAVA, "ENABLE_JAVADOC_FORMATTING", "ij_java_doc_enable_formatting", rules.javadocLayout()));
        options.add(new Option(
                Section.JAVA,
                "JD_KEEP_EMPTY_LINES",
                "ij_java_doc_keep_empty_lines",
                !rules.javadocRemoveBlankLinesInDescription()));
        options.add(new Option(
                Section.JAVA,
                "JD_ADD_BLANK_AFTER_DESCRIPTION",
                "ij_java_doc_add_blank_line_after_description",
                rules.javadocBlankLineAfterDescription()));
        options.add(new Option(
                Section.JAVA,
                "JD_ADD_BLANK_AFTER_PARM_COMMENTS",
                "ij_java_doc_add_blank_line_after_param_comments",
                rules.javadocBlankLineAfterParams()));
        options.add(new Option(
                Section.JAVA,
                "JD_ADD_BLANK_AFTER_RETURN",
                "ij_java_doc_add_blank_line_after_return",
                rules.javadocBlankLineAfterReturn()));
        // IntelliJ either aligns tag descriptions or uses one space; Tailorbird never aligns them.
        options.add(new Option(Section.JAVA, "JD_ALIGN_PARAM_COMMENTS", "ij_java_doc_align_param_comments", false));
        options.add(
                new Option(Section.JAVA, "JD_ALIGN_EXCEPTION_COMMENTS", "ij_java_doc_align_exception_comments", false));
        // Tailorbird never re-wraps JavaDoc and never adds <p>.
        options.add(new Option(Section.JAVA, "JD_P_AT_EMPTY_LINES", "ij_java_doc_add_p_tag_on_empty_lines", false));
        options.add(new Option(
                Section.JAVA, "JD_DO_NOT_WRAP_ONE_LINE_COMMENTS", "ij_java_doc_do_not_wrap_if_one_line", true));
        return options;
    }

    private static void appendOptions(StringBuilder xml, List<Option> options, Section section, String indent) {
        for (Option option : options) {
            if (option.section == section) {
                xml.append(indent)
                        .append("<option name=\"")
                        .append(option.ideaName)
                        .append("\" value=\"")
                        .append(option.value)
                        .append("\" />\n");
            }
        }
    }

    /** One line of IntelliJ's import layout: a group of imports, or a blank line between groups. */
    private static final class ImportEntry {
        /** Package prefix; empty for "all other imports". Null for a blank line. */
        @Nullable
        final String prefix;

        final boolean isStatic;

        private ImportEntry(@Nullable String prefix, boolean isStatic) {
            this.prefix = prefix;
            this.isStatic = isStatic;
        }

        static ImportEntry blankLine() {
            return new ImportEntry(null, false);
        }

        String xml() {
            if (prefix == null) {
                return "<emptyLine />";
            }
            return "<package name=\"" + prefix + "\" withSubpackages=\"true\" static=\"" + isStatic + "\" />";
        }

        String editorConfig() {
            if (prefix == null) {
                return "|";
            }
            String pattern = prefix.isEmpty() ? "*" : prefix + ".**";
            return isStatic ? "$" + pattern : pattern;
        }
    }

    private static List<ImportEntry> importLayout(TailorbirdRules rules) {
        List<String> groups = new ArrayList<>(rules.importGroups());
        // Imports that match no group go last.
        if (!groups.contains(TailorbirdRules.OTHER_IMPORTS)) {
            groups.add(TailorbirdRules.OTHER_IMPORTS);
        }
        List<ImportEntry> entries = new ArrayList<>();
        for (String group : groups) {
            if (!entries.isEmpty() && rules.blankLineBetweenImportGroups()) {
                entries.add(ImportEntry.blankLine());
            }
            if (group.equals(TailorbirdRules.STATIC_IMPORTS)) {
                entries.add(new ImportEntry("", true));
            } else if (group.equals(TailorbirdRules.OTHER_IMPORTS)) {
                entries.add(new ImportEntry("", false));
            } else {
                entries.add(new ImportEntry(group, false));
            }
        }
        return entries;
    }
}
