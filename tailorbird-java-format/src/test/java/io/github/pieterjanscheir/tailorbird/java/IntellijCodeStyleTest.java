package io.github.pieterjanscheir.tailorbird.java;

import static org.assertj.core.api.Assertions.assertThat;
import static org.assertj.core.api.Assertions.assertThatThrownBy;

import com.google.common.collect.ImmutableList;
import java.io.ByteArrayInputStream;
import java.io.PrintWriter;
import java.io.StringWriter;
import java.nio.file.Files;
import java.nio.file.Path;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.io.TempDir;

/**
 * The exported options themselves are checked against IntelliJ's real formatter by
 * {@code .github/scripts/intellij-style-check.sh}; these tests pin the mapping and the command line.
 */
class IntellijCodeStyleTest {

    @Test
    void scheme_for_the_defaults() {
        String xml = IntellijCodeStyle.export(TailorbirdRules.defaults(), IntellijCodeStyle.Format.INTELLIJ_STYLE);

        assertThat(xml)
                .startsWith("<!-- Generated by Tailorbird from tailorbird.yml. -->\n<code_scheme name=\"Tailorbird\"")
                .contains("<option name=\"RIGHT_MARGIN\" value=\"120\" />")
                .contains("<option name=\"INDENT_SIZE\" value=\"4\" />")
                .contains("<option name=\"CONTINUATION_INDENT_SIZE\" value=\"4\" />")
                .contains("<option name=\"SPACE_BEFORE_IF_PARENTHESES\" value=\"false\" />")
                .contains("<option name=\"SPACE_BEFORE_SYNCHRONIZED_PARENTHESES\" value=\"false\" />")
                .contains("<option name=\"SPACE_WITHIN_ARRAY_INITIALIZER_BRACES\" value=\"true\" />")
                .contains("<option name=\"CALL_PARAMETERS_RPAREN_ON_NEXT_LINE\" value=\"true\" />")
                .contains("<option name=\"KEEP_CONTROL_STATEMENT_IN_ONE_LINE\" value=\"false\" />")
                .contains("<option name=\"KEEP_BLANK_LINES_IN_CODE\" value=\"0\" />")
                .contains("<option name=\"BLANK_LINES_AFTER_CLASS_HEADER\" value=\"1\" />")
                .contains("<option name=\"BLANK_LINES_AROUND_FIELD\" value=\"0\" />")
                .contains("<option name=\"JD_ADD_BLANK_AFTER_PARM_COMMENTS\" value=\"true\" />")
                .contains("""
                            <package name="" withSubpackages="true" static="true" />
                            <emptyLine />
                            <package name="java" withSubpackages="true" static="false" />
                            <emptyLine />
                            <package name="javax" withSubpackages="true" static="false" />
                            <emptyLine />
                            <package name="org" withSubpackages="true" static="false" />
                            <emptyLine />
                            <package name="com" withSubpackages="true" static="false" />
                            <emptyLine />
                            <package name="" withSubpackages="true" static="false" />
                    """);
    }

    @Test
    void scheme_follows_the_settings() {
        TailorbirdRules rules = TailorbirdConfig.parse("""
            lineLength: 100
            indent: 2
            continuationIndent: 8
            spaceAfterControlKeyword: true
            arrayInitializerBraceSpaces: false
            closingParenOnOwnLine: false
            bodyWithoutBracesOnOwnLine: false
            blankLines:
              keepTyped: true
              aroundClassBody: false
              betweenFields: true
              aroundInterfaceMethods: true
            javadoc:
              enabled: false
            """, "test");

        String xml = IntellijCodeStyle.export(rules, IntellijCodeStyle.Format.INTELLIJ_STYLE);

        assertThat(xml)
                .contains("<option name=\"RIGHT_MARGIN\" value=\"100\" />")
                .contains("<option name=\"INDENT_SIZE\" value=\"2\" />")
                .contains("<option name=\"CONTINUATION_INDENT_SIZE\" value=\"8\" />")
                .contains("<option name=\"SPACE_BEFORE_IF_PARENTHESES\" value=\"true\" />")
                .contains("<option name=\"SPACE_WITHIN_ARRAY_INITIALIZER_BRACES\" value=\"false\" />")
                .contains("<option name=\"CALL_PARAMETERS_RPAREN_ON_NEXT_LINE\" value=\"false\" />")
                .contains("<option name=\"KEEP_CONTROL_STATEMENT_IN_ONE_LINE\" value=\"true\" />")
                .contains("<option name=\"KEEP_BLANK_LINES_IN_CODE\" value=\"1\" />")
                .contains("<option name=\"BLANK_LINES_AFTER_CLASS_HEADER\" value=\"0\" />")
                .contains("<option name=\"BLANK_LINES_AROUND_FIELD\" value=\"1\" />")
                .contains("<option name=\"BLANK_LINES_AROUND_METHOD_IN_INTERFACE\" value=\"1\" />")
                .contains("<option name=\"ENABLE_JAVADOC_FORMATTING\" value=\"false\" />");
    }

    @Test
    void editorconfig_for_the_defaults() {
        String editorConfig =
                IntellijCodeStyle.export(TailorbirdRules.defaults(), IntellijCodeStyle.Format.EDITORCONFIG);

        assertThat(editorConfig)
                .startsWith("# Generated by Tailorbird from tailorbird.yml.\n[*.java]\nindent_style = space\n")
                .contains("max_line_length = 120\n")
                .contains("indent_size = 4\n")
                .contains("ij_continuation_indent_size = 4\n")
                .contains("ij_java_space_before_if_parentheses = false\n")
                .contains("ij_java_spaces_within_array_initializer_braces = true\n")
                .contains("ij_java_keep_blank_lines_in_code = 0\n")
                .contains("ij_java_doc_add_blank_line_after_param_comments = true\n")
                .endsWith("ij_java_imports_layout = $*,|,java.**,|,javax.**,|,org.**,|,com.**,|,*\n");
    }

    @Test
    void import_layout_keeps_the_group_order() {
        TailorbirdRules rules =
                rules(builder -> builder.importGroups(ImmutableList.of("java", "com.example", "*", "static")));

        assertThat(IntellijCodeStyle.export(rules, IntellijCodeStyle.Format.EDITORCONFIG))
                .contains("ij_java_layout_static_imports_separately = true\n")
                .endsWith("ij_java_imports_layout = java.**,|,com.example.**,|,*,|,$*\n");
    }

    @Test
    void import_layout_without_blank_lines_between_groups() {
        TailorbirdRules rules = rules(builder -> builder.blankLineBetweenImportGroups(false));

        assertThat(IntellijCodeStyle.export(rules, IntellijCodeStyle.Format.EDITORCONFIG))
                .endsWith("ij_java_imports_layout = $*,java.**,javax.**,org.**,com.**,*\n");
    }

    @Test
    void import_layout_without_a_static_group_sorts_static_imports_with_the_others() {
        TailorbirdRules rules = rules(builder -> builder.importGroups(ImmutableList.of("java", "*")));

        assertThat(IntellijCodeStyle.export(rules, IntellijCodeStyle.Format.EDITORCONFIG))
                .contains("ij_java_layout_static_imports_separately = false\n")
                .endsWith("ij_java_imports_layout = java.**,|,*\n");
    }

    @Test
    void import_layout_puts_unmatched_imports_last() {
        TailorbirdRules rules = rules(builder -> builder.importGroups(ImmutableList.of("static", "java")));

        assertThat(IntellijCodeStyle.export(rules, IntellijCodeStyle.Format.EDITORCONFIG))
                .endsWith("ij_java_imports_layout = $*,|,java.**,|,*\n");
    }

    @Test
    void every_default_setting_is_expressible() {
        assertThat(IntellijCodeStyle.unsupported(TailorbirdRules.defaults())).isEmpty();
        assertThat(IntellijCodeStyle.unsupported(
                        TailorbirdRules.builder(TailorbirdRules.Preset.PALANTIR).build()))
                .isEmpty();
    }

    @Test
    void reports_settings_intellij_cannot_express() {
        TailorbirdRules rules =
                rules(builder -> builder.javadocSingleSpaceAfterTagName(false).blankLinesAroundFieldsWithJavadoc(true));

        assertThat(IntellijCodeStyle.unsupported(rules))
                .hasSize(2)
                .anySatisfy(note -> assertThat(note).startsWith("blankLines.aroundFieldsWithJavadoc:"))
                .anySatisfy(note -> assertThat(note).startsWith("javadoc.singleSpaceAfterTagName: false:"));
        assertThat(IntellijCodeStyle.export(rules, IntellijCodeStyle.Format.INTELLIJ_STYLE))
                .contains("Not expressible: javadoc.singleSpaceAfterTagName");
        assertThat(IntellijCodeStyle.export(rules, IntellijCodeStyle.Format.EDITORCONFIG))
                .contains("# Not expressible: blankLines.aroundFieldsWithJavadoc");
    }

    @Test
    void blank_lines_around_javadoc_fields_are_expressible_when_other_rules_cover_them() {
        // IntelliJ keeps typed blank lines, or adds them around every field.
        assertThat(IntellijCodeStyle.unsupported(rules(builder ->
                        builder.blankLinesAroundFieldsWithJavadoc(true).keepTypedBlankLines(true))))
                .isEmpty();
        assertThat(IntellijCodeStyle.unsupported(rules(builder ->
                        builder.blankLinesAroundFieldsWithJavadoc(true).blankLinesBetweenFields(true))))
                .isEmpty();
        // Without JavaDoc formatting, the tag spacing isn't touched by either formatter.
        assertThat(IntellijCodeStyle.unsupported(
                        rules(builder -> builder.javadocLayout(false).javadocSingleSpaceAfterTagName(false))))
                .isEmpty();
    }

    @Test
    void command_line_exports_the_intellij_style() throws Exception {
        assertThat(run("--export-intellij-style"))
                .isEqualTo(
                        IntellijCodeStyle.export(TailorbirdRules.defaults(), IntellijCodeStyle.Format.INTELLIJ_STYLE));
    }

    @Test
    void command_line_exports_the_editorconfig_from_a_config_file(@TempDir Path tempDir) throws Exception {
        Path config = tempDir.resolve("tailorbird.yml");
        Files.writeString(config, "indent: 2\n");

        assertThat(run("--config", config.toString(), "--export-editorconfig"))
                .isEqualTo(IntellijCodeStyle.export(
                        TailorbirdRules.builder().indent(2).build(), IntellijCodeStyle.Format.EDITORCONFIG));
    }

    @Test
    void command_line_export_takes_no_files() {
        assertThatThrownBy(() -> run("--export-intellij-style", "Example.java"))
                .isInstanceOf(UsageException.class)
                .hasMessageContaining("take no files to format");
        assertThatThrownBy(() -> run("--export-intellij-style", "--export-editorconfig"))
                .isInstanceOf(UsageException.class)
                .hasMessageContaining("Cannot use both --export-intellij-style and --export-editorconfig");
    }

    private static TailorbirdRules rules(java.util.function.UnaryOperator<TailorbirdRules.Builder> settings) {
        return settings.apply(TailorbirdRules.builder()).build();
    }

    private static String run(String... args) throws UsageException {
        StringWriter out = new StringWriter();
        StringWriter err = new StringWriter();
        Main main =
                new Main(new PrintWriter(out, true), new PrintWriter(err, true), new ByteArrayInputStream(new byte[0]));
        int exitCode = main.format(args);
        assertThat(exitCode).as(err.toString()).isZero();
        return out.toString();
    }
}
